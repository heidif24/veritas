export function getLocaleFromCookie(cookieHeader?: string | null): Locale {
  const match = cookieHeader?.match(/(?:^|;\s*)veritas_locale=([a-z]{2})/);
  const code = (match?.[1] || "en") as Locale;
  return LOCALES.some((l) => l.code === code) ? code : "en";
}
